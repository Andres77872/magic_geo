"""Causal-replay validation for the population, conflict, and dynasty models.

``validate_civilization_geography_replay`` recomputes every population region,
conflict, and dynasty record from the raw cell/region/culture/event inputs and
compares them field by field. The canonical controls use generated worlds;
explicitly labeled stage tests exercise controlled downstream inputs separately.

Every failure case below therefore follows the same three-legged shape, applied
by :meth:`_assert_only_the_tamper_fails`:

1. the untampered canonical world replays clean,
2. one tamper makes the validator return the single fixed failure string,
3. undoing that one tamper makes the very same payload replay clean again.

Leg 3 is what keeps these tests honest: a tamper that was never the cause of the
failure (or an assertion that could not fail) makes leg 1 or leg 3 blow up.

Regime note: at 128 cells the world has one political region, one culture, one
population region, one dynasty, and — because ``borders`` is empty — zero
conflicts, so the canonical world alone cannot reach the conflict record builder
or a second dynasty generation. Three further payloads reach those:

* ``mid_512`` (canonical, two regions) carries one real conflict
  record, so its fields can be tampered with;
* fabricated border segments appended to the 128-cell world drive the candidate
  filters and the conflict chronology without disturbing the population replay
  (borders are not a population input, which is what keeps the replay reaching
  the conflict builder at all);
* two retained one-off current-model configurations — :data:`MULTI_DYNASTY_WORLD`
  and :data:`RIVAL_REGION_WORLD` — clear the model's 0.36 succession threshold,
  giving their regions a second dynasty generation, collapse reasons and lineage
  links. Their physical worlds remain unmodified; a separate dynasty-stage
  route-removal control preserves trade-decline priority coverage.
"""

from __future__ import annotations

from typing import Any
from unittest import TestCase

from support import worlds

from magic_geo.api import generate_world
from magic_geo.civilization_geography_validation import (
    _dynasty_matches,
    _dynasty_records,
    validate_civilization_geography_replay,
)

#: The single message the validator returns for any mismatch.
FAILURE = "population, conflict, or dynasty model causal replay invalid"

CANONICAL_WORLD = "replay_128"

#: The smallest canonical world that draws political borders, and therefore the
#: one used here to tamper a conflict record.
BORDERED_WORLD = "mid_512"

#: One-off configurations (``mesh.cell_count``, ``run.seed``) generated by this
#: file alone. ``MULTI_DYNASTY_WORLD`` gives both its regions a second dynasty
#: generation; ``RIVAL_REGION_WORLD`` has three regions, which puts a region in two
#: conflicts at once and pushes its conflict pressure past 0.45.
# Both regional lines still split under current seasonal climate. Their routes
# now keep both first-generation collapse reasons in the succession-crisis branch.
MULTI_DYNASTY_WORLD = (1280, 3015)
RIVAL_REGION_WORLD = (2048, 1234)

#: Model identities published in ``README.md`` for these three subsystems.
POPULATION_REGION_MODEL = "causal_area_weighted_capacity_occupancy_population_regions_v1"
CONFLICT_MODEL = "causal_border_pair_pressure_trade_conflict_selection_v1"
DYNASTY_MODEL = "causal_foundation_continuity_pressure_dynasty_lineages_v1"

_MISSING = object()

#: Generated at most once per process, like :mod:`support.worlds` does for the
#: canonical set. Callers must not mutate the shared payload.
_ONE_OFF_WORLDS: dict[tuple[int, int], dict[str, Any]] = {}


def _one_off_world(config: tuple[int, int]) -> dict[str, Any]:
    """The shared one-off world for ``(cell_count, seed)``; never mutate it."""
    if config not in _ONE_OFF_WORLDS:
        cell_count, seed = config
        _ONE_OFF_WORLDS[config] = generate_world(
            worlds.build_config(**{"mesh.cell_count": cell_count, "run.seed": seed})
        )
    return _ONE_OFF_WORLDS[config]


def _with_private_records(world: dict[str, Any], family: str) -> dict[str, Any]:
    """A payload sharing ``world`` except for private copies of ``family``.

    Deep-copying a 2048-cell world for every tamper costs more than generating
    it, and these tampers only ever rewrite a top-level field of one record, so
    copying that one family is enough to leave the shared world untouched.
    """
    payload = dict(world)
    payload[family] = [dict(record) for record in world[family]]
    return payload


class CivilizationGeographyReplayValidationTests(TestCase):
    def _clean_world(self) -> dict[str, Any]:
        """A private copy of the canonical world, proven clean before tampering."""
        world = worlds.cached_world(CANONICAL_WORLD)
        self.assertEqual(
            validate_civilization_geography_replay(world),
            [],
            "the untampered copy must replay clean, otherwise no tamper proves anything",
        )
        return world

    def _assert_only_the_tamper_fails(
        self,
        world: dict[str, Any],
        mapping: dict[str, Any],
        key: str,
        value: Any,
    ) -> None:
        """Set ``mapping[key] = value``, require the failure, undo, require clean."""
        original = mapping.get(key, _MISSING)
        self.assertNotEqual(
            original, value, f"{key!r} already holds {value!r}; this tamper changes nothing"
        )
        mapping[key] = value

        self.assertEqual(
            validate_civilization_geography_replay(world),
            [FAILURE],
            f"tampering {key!r} must be reported as a replay failure",
        )

        if original is _MISSING:
            del mapping[key]
        else:
            mapping[key] = original
        self.assertEqual(
            validate_civilization_geography_replay(world),
            [],
            f"undoing the {key!r} tamper must replay clean again, otherwise the "
            "failure above was not caused by that tamper",
        )

    def _assert_only_the_removal_fails(
        self, world: dict[str, Any], mapping: dict[str, Any], key: str
    ) -> None:
        """Delete ``mapping[key]``, require the failure, restore, require clean."""
        original = mapping.pop(key)

        self.assertEqual(
            validate_civilization_geography_replay(world),
            [FAILURE],
            f"a payload missing {key!r} must be reported as a replay failure",
        )

        mapping[key] = original
        self.assertEqual(
            validate_civilization_geography_replay(world),
            [],
            f"restoring {key!r} must replay clean again",
        )

    def _assert_only_the_list_tamper_fails(
        self, world: dict[str, Any], records: list[Any], mutate: Any, label: str
    ) -> None:
        """Mutate ``records`` in place, require the failure, restore, require clean."""
        original = list(records)
        mutate(records)
        self.assertNotEqual(records, original, f"{label} left the list unchanged")

        self.assertEqual(
            validate_civilization_geography_replay(world),
            [FAILURE],
            f"{label} must be reported as a replay failure",
        )

        records[:] = original
        self.assertEqual(
            validate_civilization_geography_replay(world),
            [],
            f"undoing {label} must replay clean again",
        )

