    def test_raw_input_tampers_break_the_replay(self) -> None:
        # The point of a causal replay is that the records are *derived*, not
        # echoed: changing an input the records were built from must invalidate
        # them even though every stored record is left untouched.
        world = self._clean_world()
        with self.subTest(raw_input="culture_continuity_index"):
            self._assert_only_the_tamper_fails(
                world, world["cultures"][0], "continuity_index", 0.01
            )
        with self.subTest(raw_input="culture_migration_pressure"):
            self._assert_only_the_tamper_fails(
                world, world["cultures"][0], "migration_pressure", 0.02
            )
        with self.subTest(raw_input="cell_flooded"):
            self._assert_only_the_tamper_fails(world, world["cells"][0], "is_water", True)
        with self.subTest(raw_input="cell_left_its_region"):
            self._assert_only_the_tamper_fails(
                world, world["cells"][0], "political_region_id", -1
            )
        with self.subTest(raw_input="state_foundation_event_year"):
            foundations = [
                event
                for event in world["historical_events"]
                if str(event.get("type", "")) == "state_foundation"
            ]
            self.assertEqual(
                len(foundations), 1, "expected exactly one state foundation to shift"
            )
            self._assert_only_the_tamper_fails(
                world, foundations[0], "year_bp", float(foundations[0]["year_bp"]) + 500.0
            )
        with self.subTest(raw_input="every_cell_fertility"):
            cells = world["cells"]
            originals = [float(cell["fertility"]) for cell in cells]
            self.assertNotEqual(
                originals, [0.99] * len(cells), "fertility already holds the tampered value"
            )
            for cell in cells:
                cell["fertility"] = 0.99

            self.assertEqual(validate_civilization_geography_replay(world), [FAILURE])

            for cell, original in zip(cells, originals, strict=True):
                cell["fertility"] = original
            self.assertEqual(
                validate_civilization_geography_replay(world),
                [],
                "restoring cell fertility must replay clean again",
            )

    def test_malformed_payloads_fail_without_raising(self) -> None:
        for name, payload in (
            ("empty_payload", {}),
            ("cells_not_a_list", {"cells": "not-a-list"}),
        ):
            with self.subTest(payload=name):
                self.assertEqual(validate_civilization_geography_replay(payload), [FAILURE])

        world = self._clean_world()
        with self.subTest(payload="conflicts_not_a_list"):
            self._assert_only_the_tamper_fails(world, world, "conflicts", {})
        with self.subTest(payload="population_record_not_a_dict"):
            records = world["population_regions"]
            self._assert_only_the_list_tamper_fails(
                world,
                records,
                lambda values: values.__setitem__(0, "not-a-dict"),
                "a non-dict population record",
            )
        with self.subTest(payload="dangling_cell_neighbor"):
            # A neighbour id that no cell owns makes the replay raise KeyError
            # inside ``_has_water_neighbor``; the validator must swallow it and
            # report the failure instead of propagating. This is the only case
            # in this file that reaches that except branch.
            self._assert_only_the_tamper_fails(
                world, world["cells"][0], "neighbors", [10**9]
            )

    def test_non_numeric_measurements_are_reported_not_raised(self) -> None:
        # Every float the validator compares goes through one tolerance helper
        # that converts the *stored* value. A payload carrying a string there
        # must be reported as a mismatch rather than raising ValueError out of
        # the helper, which is a different branch from the KeyError case above.
        world = self._clean_world()
        cases: dict[str, tuple[dict[str, Any], str]] = {
            "population_water_security": (world["population_regions"][0], "water_security_index"),
            "population_carrying_capacity": (world["population_regions"][0], "carrying_capacity"),
            "dynasty_legitimacy": (world["dynasties"][0], "legitimacy_index"),
            "summary_mean_population_pressure": (world["summary"], "mean_population_pressure"),
        }
        for name, (record, field) in cases.items():
            with self.subTest(field=name):
                self._assert_only_the_tamper_fails(world, record, field, "not-a-number")

    def test_a_cell_with_no_neighbours_has_no_local_relief(self) -> None:
        # ``_local_relief`` divides by the neighbour count, so the empty case has
        # its own early return. Zeroing the relief of one populated land cell
        # lowers that cell's hazard contribution and invalidates the region's
        # stored hazard index, population and growth rate.
        world = self._clean_world()
        cell = next(
            item
            for item in world["cells"]
            if not bool(item.get("is_water", False))
            and int(item.get("political_region_id", -1)) == 0
        )
        self.assertTrue(cell["neighbors"], "the chosen cell already has no neighbours")

        self._assert_only_the_tamper_fails(world, cell, "neighbors", [])

    def test_a_region_that_owns_no_cell_replays_as_an_empty_population(self) -> None:
        # With every cell disowned the region keeps its record but has zero area,
        # so the replay takes the early "nothing to average" path and expects an
        # all-zero population region, which the stored record is not.
        world = self._clean_world()
        cells = world["cells"]
        originals = [int(cell["political_region_id"]) for cell in cells]
        self.assertIn(0, originals, "no cell belongs to region 0, so this proves nothing")
        for cell in cells:
            cell["political_region_id"] = -1

        self.assertEqual(validate_civilization_geography_replay(world), [FAILURE])

        for cell, original in zip(cells, originals, strict=True):
            cell["political_region_id"] = original
        self.assertEqual(
            validate_civilization_geography_replay(world),
            [],
            "restoring the region membership must replay clean again",
        )

    def _fabricated_border(self, world: dict[str, Any], index: int, **overrides: Any) -> dict[str, Any]:
        """A border segment the payload never declared, appended to ``world``.

        Borders are not an input to the population replay, so appending one
        leaves the population comparison passing and lets the conflict builder
        run — which is the only way to reach it from a 128-cell world.
        """
        cells = world["cells"]
        border: dict[str, Any] = {
            "id": index,
            "cell_a": int(cells[2 * index]["id"]),
            "cell_b": int(cells[2 * index + 1]["id"]),
            "region_a": 0,
            "region_b": 1,
            "type": "mountain",
            "barrier_score": 0.9,
            "length_km": 100.0,
        }
        border.update(overrides)
        world["borders"].append(border)
        return border

    def test_a_fabricated_border_makes_the_conflict_model_expect_a_conflict(self) -> None:
        # A fabricated segment with nothing disqualifying it does invalidate the
        # payload: the model expects a conflict the payload never declared.
        world = self._clean_world()
        self.assertEqual(world["borders"], [], "the fabricated segment must be the only border")

        self._fabricated_border(world, 0)

        self.assertEqual(validate_civilization_geography_replay(world), [FAILURE])

    def test_borders_the_conflict_model_discards_leave_the_replay_clean(self) -> None:
        # Two independent candidate filters. Each case injects a *qualifying*
        # segment, breaks exactly one of its fields, and requires the replay to
        # stay clean -- then repairs that one field and requires the very same
        # segment to be fatal again. Without the repair leg a clean result would
        # also be what an injection that never happened looks like, so the third
        # leg is what ties it to the named field.
        cases: dict[str, tuple[str, Any]] = {
            # A segment missing one of its two regions or cells is skipped.
            "unknown_region": ("region_a", -1),
            "unknown_cell": ("cell_b", -1),
            # A segment whose candidate score cannot reach 0.24 is skipped: the
            # intensity floor is a clamp at zero, so a hugely negative barrier
            # leaves only the fertility term, which is at most 0.08.
            "score_below_the_candidate_threshold": ("barrier_score", -10.0),
        }
        for name, (field, disqualifying) in cases.items():
            with self.subTest(border=name):
                world = self._clean_world()
                border = self._fabricated_border(world, 0)
                qualifying = border[field]
                self.assertNotEqual(
                    qualifying,
                    disqualifying,
                    f"{field!r} already holds {disqualifying!r}; this tamper changes nothing",
                )
                border[field] = disqualifying

                self.assertEqual(
                    validate_civilization_geography_replay(world),
                    [],
                    "a discarded border candidate must not change the replay",
                )

                border[field] = qualifying
                self.assertEqual(
                    validate_civilization_geography_replay(world),
                    [FAILURE],
                    f"repairing {field!r} must make the same segment a conflict candidate "
                    "again, otherwise the clean result above proves nothing",
                )

    def test_a_conflict_between_two_unknown_regions_is_a_stalemate(self) -> None:
        # Neither region has a population record, so both sides mobilise nothing
        # and the force advantage is exactly zero — the stalemate branch of the
        # outcome model. The payload declares no conflict at all, so it fails.
        world = self._clean_world()
        self._fabricated_border(world, 0, region_a=7, region_b=8)

        self.assertEqual(validate_civilization_geography_replay(world), [FAILURE])

    def test_late_maximum_intensity_conflicts_land_in_the_oldest_era(self) -> None:
        # The chronology model dates a conflict from its intensity plus a fixed
        # offset per earlier region pair, so the oldest era (before 2400 BP) can
        # only be reached by a maximum-intensity conflict that is at least the
        # twenty-fourth pair on the list. Twenty-six fabricated pairs clear it.
        world = self._clean_world()
        for index in range(26):
            self._fabricated_border(
                world, index, region_a=100 + index, region_b=200 + index, barrier_score=5.0
            )

        self.assertEqual(validate_civilization_geography_replay(world), [FAILURE])

    def _clean_bordered_world(self) -> dict[str, Any]:
        """A private copy of the smallest canonical world that has a conflict."""
