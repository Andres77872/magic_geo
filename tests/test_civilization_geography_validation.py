    def test_conflict_record_field_tampers_are_detected(self) -> None:
        # The conflict record comparison the 128-cell world can never reach:
        # exact keys first, then the tolerance keys, then the relative ones.
        world = self._clean_bordered_world()
        record = world["conflicts"][0]
        cases: dict[str, Any] = {
            "era_id": 0,
            "region_a": 5,
            "culture_b": -1,
            "cause": "sacred_site",
            "outcome": "stalemate",
            "contested_cell_id": 0,
            "start_year_bp": float(record["start_year_bp"]) + 5.0,
            "war_duration_years": float(record["war_duration_years"]) + 5.0,
            "intensity": float(record["intensity"]) - 0.02,
            "water_stress": float(record["water_stress"]) - 0.02,
            "casualty_rate": float(record["casualty_rate"]) + 0.02,
            "logistics_strain_index": float(record["logistics_strain_index"]) - 0.02,
            "economic_disruption_index": float(record["economic_disruption_index"]) - 0.02,
            "mobilized_population": float(record["mobilized_population"]) * 1.5,
            "region_a_force_estimate": float(record["region_a_force_estimate"]) * 1.5,
            "estimated_casualties": float(record["estimated_casualties"]) * 1.5,
        }
        for field, value in cases.items():
            with self.subTest(conflict_field=field):
                self._assert_only_the_tamper_fails(world, record, field, value)

    def test_borders_stripped_of_their_regions_erase_the_conflict(self) -> None:
        # The mirror of the fabricated-border cases: with every real segment
        # disqualified the model expects no conflict at all, while the payload
        # still declares one.
        world = self._clean_bordered_world()
        borders = world["borders"]
        originals = [int(border["region_a"]) for border in borders]
        self.assertTrue(all(value >= 0 for value in originals), "a border already lacks a region")
        for border in borders:
            border["region_a"] = -1

        self.assertEqual(validate_civilization_geography_replay(world), [FAILURE])

        for border, original in zip(borders, originals, strict=True):
            border["region_a"] = original
        self.assertEqual(validate_civilization_geography_replay(world), [])

    def test_multi_generation_dynasties_replay_and_carry_a_collapse_reason(self) -> None:
        # A world whose succession pressure clears 0.36 splits a region's line
        # into two dynasties, which is what makes the collapse-reason ladder and
        # the parent/child/successor links reachable at all: only a dynasty that
        # is *not* the last of its region gets a reason other than "continuity".
        world = _one_off_world(MULTI_DYNASTY_WORLD)
        self.assertEqual(
            validate_civilization_geography_replay(world),
            [],
            "the one-off multi-dynasty world must replay clean",
        )
        reasons = [str(dynasty["collapse_reason"]) for dynasty in world["dynasties"]]
        self.assertTrue(all(int(region["route_count"]) > 0 for region in world["political_regions"]))
        self.assertTrue(all(0.36 < float(d["succession_pressure"]) < 0.66 for d in world["dynasties"] if d["lineage_depth"] == 0))
        self.assertEqual(reasons, ["succession_crisis", "continuity", "succession_crisis", "continuity"])
        self.assertEqual([int(d["lineage_depth"]) for d in world["dynasties"]], [0, 1, 0, 1])
        self.assertEqual([int(d["parent_dynasty_id"]) for d in world["dynasties"]], [-1, 0, -1, 2])
        self.assertEqual([int(d["successor_dynasty_id"]) for d in world["dynasties"]], [1, -1, 3, -1])

        with self.subTest(tamper="collapse_reason"):
            payload = _with_private_records(world, "dynasties")
            payload["dynasties"][0]["collapse_reason"] = "conflict_defeat"

            self.assertEqual(validate_civilization_geography_replay(payload), [FAILURE])

        with self.subTest(tamper="successor_link"):
            payload = _with_private_records(world, "dynasties")
            payload["dynasties"][2]["successor_dynasty_id"] = -1

            self.assertEqual(validate_civilization_geography_replay(payload), [FAILURE])

        with self.subTest(tamper="region_retyped_as_a_mining_domain"):
            # The reason ladder reads the region's type, which is not an input to
            # the population or conflict replay, so this single field flips
            # "succession_crisis" to "resource_shock" and nothing else.
            payload = _with_private_records(world, "political_regions")
            self.assertNotEqual(payload["political_regions"][0]["type"], "mining_domain")
            self.assertNotEqual(payload["political_regions"][0]["dominant_resource"], "none")
            payload["political_regions"][0]["type"] = "mining_domain"

            self.assertEqual(validate_civilization_geography_replay(payload), [FAILURE])

    def test_route_removal_changes_the_isolated_dynasty_stage_to_trade_decline(self) -> None:
        # Downstream-only counterfactual: route removal would also affect the
        # population/conflict stages in a full world. Hold their already-derived
        # inputs fixed here and validate only dynasty records, never the altered
        # payload as a complete physical or civilization world.
        world = _one_off_world(MULTI_DYNASTY_WORLD)
        regions = [dict(region) for region in world["political_regions"]]
        region_id = 0
        region = regions[region_id]
        self.assertGreater(region["route_count"], 0)
        self.assertNotEqual(region["type"], "mining_domain")
        population = next(p for p in world["population_regions"] if p["region_id"] == region_id)
        self.assertLess(population["population_pressure"], 0.68)
        conflict_pressure = sum(c["intensity"] for c in world["conflicts"] if region_id in (c["region_a"], c["region_b"])) / 3.0
        self.assertLess(conflict_pressure, 0.45)
        region["route_count"] = 0

        # With no clamp or generation threshold crossed, the declared 0.10
        # route term changes pressure by +.10, legitimacy by -.22*.10, and
        # continuity by .34*(-.022) + .18*(-.10). All other inputs stay fixed.
        expected = [dict(record) for record in world["dynasties"]]
        changed = [record for record in expected if record["region_id"] == region_id]
        self.assertEqual(len(changed), 2)
        self.assertLess(changed[0]["succession_pressure"] + 0.10, 0.66)
        for record in changed:
            self.assertGreater(record["legitimacy_index"], 0.022)
            self.assertGreater(record["dynastic_continuity_index"], 0.02548)
            record["succession_pressure"] += 0.10
            record["legitimacy_index"] -= 0.022
            record["dynastic_continuity_index"] -= 0.02548
        changed[0]["collapse_reason"] = "trade_decline"
        replayed = _dynasty_records(regions, world["cultures"], world["historical_events"], world["population_regions"], world["conflicts"])
        self.assertEqual([record["collapse_reason"] for record in replayed], ["trade_decline", "continuity", "succession_crisis", "continuity"])
        self.assertEqual(len(replayed), len(expected))
        self.assertTrue(all(_dynasty_matches(actual, replay) for actual, replay in zip(expected, replayed, strict=True)))
        changed[0]["collapse_reason"] = "succession_crisis"
        self.assertFalse(_dynasty_matches(changed[0], replayed[0]))
        changed[0]["collapse_reason"] = "trade_decline"
        self.assertTrue(_dynasty_matches(changed[0], replayed[0]))
        self.assertGreater(world["political_regions"][region_id]["route_count"], 0)
        self.assertEqual(world["dynasties"][0]["collapse_reason"], "succession_crisis")

    def test_three_rival_regions_replay_with_conflict_defeat_dynasties(self) -> None:
        # Three regions put every region in two conflicts at once, which is the
        # only way its conflict pressure passes 0.45 and the collapse reason
        # becomes "conflict_defeat". Scoring this world's many border segments
        # also exercises exhaustion and a decisive region-B victory among the
        # selected records. Conflict-defeat collapse depends on accumulated
        # intensity, rather than requiring every selected outcome to be exhaustion.
        world = _one_off_world(RIVAL_REGION_WORLD)
        self.assertEqual(
            validate_civilization_geography_replay(world),
            [],
            "the one-off three-region world must replay clean",
        )
        self.assertEqual(len(world["political_regions"]), 3)
        self.assertEqual(len(world["conflicts"]), 3)
        for region in world["political_regions"]:
            regional = [c for c in world["conflicts"] if region["id"] in (c["region_a"], c["region_b"])]
            self.assertEqual(len(regional), 2)
            self.assertGreater(sum(c["intensity"] for c in regional) / 3.0, 0.45)
        self.assertEqual(
            [str(dynasty["collapse_reason"]) for dynasty in world["dynasties"]],
            ["conflict_defeat", "continuity"] * 3,
        )
        self.assertEqual(
            [str(conflict["outcome"]) for conflict in world["conflicts"]],
            ["exhaustion", "exhaustion", "region_b_victory"],
        )
        for conflict in world["conflicts"][:2]:
            self.assertGreater(conflict["logistics_strain_index"], 0.72)
            self.assertGreater(conflict["intensity"], 0.58)
        victory = world["conflicts"][2]
        self.assertLess(victory["logistics_strain_index"], 0.72)
        self.assertGreater(victory["region_b_force_estimate"], victory["region_a_force_estimate"])

        with self.subTest(tamper="conflict_outcome"):
            payload = _with_private_records(world, "conflicts")
            payload["conflicts"][0]["outcome"] = "border_shift"

            self.assertEqual(validate_civilization_geography_replay(payload), [FAILURE])

        with self.subTest(tamper="collapse_reason"):
            payload = _with_private_records(world, "dynasties")
            payload["dynasties"][0]["collapse_reason"] = "succession_crisis"

            self.assertEqual(validate_civilization_geography_replay(payload), [FAILURE])
