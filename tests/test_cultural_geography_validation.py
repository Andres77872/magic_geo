    def test_a_language_that_inherits_a_family_gets_a_derived_divergence_age(self) -> None:
        # The lineage model only gives a language a parent when another language
        # of the *same family* has more area, and then dates it from its own
        # isolation and trade contact instead of the root formula. The canonical
        # world has a single language, so this needs a one-off world.
        payload = _one_off_payload(SHARED_FAMILY_WORLD)
        self.assertEqual(
            validate_cultural_geography_replay(payload),
            [],
            "the one-off shared-family world must replay clean",
        )
        languages = payload["language_regions"]
        self.assertEqual(len(languages), 2)
        self.assertEqual({str(language["family"]) for language in languages}, {"coastal"})
        self.assertEqual(int(languages[0]["parent_language_region_id"]), -1)
        self.assertEqual(int(languages[1]["parent_language_region_id"]), 0)
        self.assertEqual(int(languages[1]["lineage_depth"]), 1)

        for field, delta in (("divergence_age_years", 40.0), ("sound_shift_index", 0.02)):
            with self.subTest(child_field=field):
                payload = _one_off_payload(SHARED_FAMILY_WORLD)
                _shift(payload["language_regions"][1], field, delta)

                self.assertEqual(validate_cultural_geography_replay(payload), [FAILURE])
