    def test_duplicate_cell_ids_are_rejected(self) -> None:
        # ``cells`` is indexed by id, so a collision would silently drop a cell
        # from the replay; the validator compares the two counts instead.
        self.assert_rejected(lambda p: _set(p["cells"][1], "id", p["cells"][0]["id"]))

    def test_non_list_collections_are_rejected_before_they_can_be_indexed(self) -> None:
        # Each replacement has the *same length* as the list it replaces, so the
        # record-count checks cannot explain the rejection: only the type guard
        # can. Without it the validator would reach ``str.get`` and raise.
        def as_string(key: str) -> Mutation:
            def mutate(payload: dict[str, Any]) -> None:
                count = len(payload[key])
                self.assertGreater(count, 0, f"{key} is empty, so length parity proves nothing")
                payload[key] = "x" * count

            return mutate

        for key in ("cells", "cultures", "language_regions", "sacred_areas", "ruins", "settlements"):
            with self.subTest(collection=key):
                self.assert_rejected(as_string(key))

