"""Causal-replay coverage for :mod:`magic_geo.cultural_geography_validation`.

``validate_cultural_geography_replay`` recomputes the whole deterministic
cultural model (culture regions, language regions, sacred areas and ruins) from
the generated world and compares it record by record, so a passing payload
cannot be hand-built: the happy path runs the real canonical world, and every
failure case starts from that world and applies exactly one tamper.

Two devices keep the failure cases honest.  :func:`_set` refuses to write a
value a field already holds, so a tamper can never silently become a no-op that
"passes" against an untouched world.  :meth:`assert_rejected` re-validates the
pristine copy before mutating it, so a rejection is always attributable to the
tamper rather than to drift in the generated world.  The complementary
:meth:`assert_accepted` cases pin the other side of every tolerance: the
validator compares floats with per-field tolerances and ignores unknown keys,
so the rejections below cannot be explained by "any edit at all fails".
"""

from __future__ import annotations

import copy
from typing import Any, Callable
from unittest import TestCase

from support import worlds

from magic_geo.api import generate_world
from magic_geo.cultural_geography import (
    enrich_world_with_cultural_geography_models,
)
from magic_geo.cultural_geography_validation import validate_cultural_geography_replay

#: The single message the validator returns for any mismatch.
FAILURE = "cultural geography model or causal replay invalid"

CANONICAL_WORLD = "replay_128"

#: A canonical world with two political regions, so a border segment can join
#: two different cultures.
TWO_REGION_WORLD = "mid_512"

#: The current seasonal fixture with two separate languages before a new
#: interregional trade connection. Two political regions alone do not ensure it.
TWO_LANGUAGE_WORLD = "language_contact_256"

#: A one-off configuration (``mesh.cell_count``, ``run.seed``) generated by this
#: file alone: the smallest found whose two languages share one family, which is
#: what gives the younger one a parent and a *derived* divergence age rather than
#: the root age formula.
SHARED_FAMILY_WORLD = (192, 2718)

#: The top-level keys the validator reads. Every tamper needs its own private
#: copy, and deep-copying the whole 191-key world 100+ times dominates this
#: file's runtime, so the copies are restricted to these keys. Nothing is
#: taken on trust: :meth:`assert_rejected` re-validates each copy while it is
#: still pristine and :meth:`assert_accepted` expects a clean replay, so a key
#: the validator starts reading later surfaces as an immediate failure here
#: rather than as a silently weakened test.
REPLAY_KEYS = (
    "summary",
    "cells",
    "political_regions",
    "borders",
    "trade_flows",
    "settlements",
    "cultures",
    "language_regions",
    "sacred_areas",
    "ruins",
    "culture_region_model",
    "language_region_model",
    "cultural_site_model",
)

Mutation = Callable[[dict[str, Any]], Any]

#: A land signature with no sacred trigger of its own: lowland, no resource, no
#: river or lake, no ice and no tectonics. The sacred cases below add exactly the
#: field each branch is named for. ``is_closed_basin`` and the wet-and-fertile
#: pair keep the significance above the model's selection floor, so the sites are
#: still ranked and classified rather than dropped from the payload.
NEUTRAL_LAND: dict[str, Any] = {
    "resource": "none",
    "elevation_m": 200.0,
    "landform": "plain",
    "is_river": False,
    "is_lake": False,
    "water_body_type": "land",
    "is_closed_basin": True,
    "fertility": 0.8,
    "precipitation_mm_y": 700.0,
    "ice_thickness_m": 0.0,
    "boundary_convergent": 0.0,
    "boundary_transform": 0.0,
    "settlement_score": 0.5,
    "biome": "steppe",
}

#: The same, retuned for ruins: a ruin needs a slightly richer history to clear
#: its own selection floor (hence the resource, which is not one of the mined
#: ones and so does not answer the first rung of the type ladder), and no closed
#: basin, which would otherwise explain the abandonment before the rungs below.
NEUTRAL_RUIN_LAND: dict[str, Any] = {
    **NEUTRAL_LAND,
    "resource": "sedimentary_fuels",
    "is_closed_basin": False,
}


def _set(record: dict[str, Any], key: str, value: Any) -> None:
    """Write ``value`` to ``key``, refusing a write that changes nothing.

    A tamper that assigns the value the field already holds leaves a valid
    payload behind, and the test asserting rejection would then fail for a
    confusing reason (or, worse, a sibling assertion would carry it).  Raising
    here turns that mistake into an explicit error naming the field.
    """
    if key not in record:
        raise AssertionError(f"expected field {key!r} on record {sorted(record)}")
    if record[key] == value:
        raise AssertionError(f"tamper is a no-op: {key!r} is already {value!r}")
    record[key] = value


def _shift(record: dict[str, Any], key: str, delta: float) -> None:
    """Move a numeric field by ``delta``, which must be outside its tolerance."""
    if delta == 0.0:
        raise AssertionError("a zero shift is not a tamper")
    _set(record, key, float(record[key]) + delta)


def _replay_payload() -> dict[str, Any]:
    """A private, mutable copy of the canonical world's replay inputs."""
    return _payload_from(worlds.cached_world_readonly(CANONICAL_WORLD))


def _payload_from(world: dict[str, Any]) -> dict[str, Any]:
    """A private, mutable copy of ``world`` restricted to the replay inputs."""
    return copy.deepcopy({key: world[key] for key in REPLAY_KEYS})


#: Generated at most once per process, like :mod:`support.worlds` does for the
#: canonical set.
_ONE_OFF_WORLDS: dict[tuple[int, int], dict[str, Any]] = {}


def _one_off_payload(config: tuple[int, int]) -> dict[str, Any]:
    """The replay inputs of the one-off world for ``(cell_count, seed)``."""
    if config not in _ONE_OFF_WORLDS:
        cell_count, seed = config
        _ONE_OFF_WORLDS[config] = generate_world(
            worlds.build_config(**{"mesh.cell_count": cell_count, "run.seed": seed})
        )
    return _payload_from(_ONE_OFF_WORLDS[config])


def _model_stub(**overrides: Any) -> dict[str, Any]:
    """A minimal payload carrying the real model descriptors.

    Built through the producer, :func:`enrich_world_with_cultural_geography_models`,
    so it clears the descriptor gate at the top of the validator.  Overrides are
    applied *after* enrichment, so a deliberately malformed collection still
    reaches the shape guards below that gate instead of being rejected for a
    missing descriptor.
    """
    payload = enrich_world_with_cultural_geography_models(
        {
            "cells": [],
            "cultures": [],
            "language_regions": [],
            "sacred_areas": [],
            "ruins": [],
        }
    )
    payload.update(overrides)
    return payload


class CulturalGeographyReplayValidationTests(TestCase):
    def assert_rejected(self, mutate: Mutation) -> None:
        """One tamper on a private copy of the canonical world must be caught.

        The pristine copy is validated first: without that control an expected
        failure could come from the world rather than from ``mutate``.
        """
        payload = _replay_payload()
        self.assertEqual(
            validate_cultural_geography_replay(payload),
            [],
            "untampered copy must replay cleanly or the tamper proves nothing",
        )

        mutate(payload)

        self.assertEqual(validate_cultural_geography_replay(payload), [FAILURE])

    def assert_accepted(self, mutate: Mutation) -> None:
        """An edit the validator is specified to tolerate must still replay."""
        payload = _replay_payload()
        mutate(payload)

        self.assertEqual(validate_cultural_geography_replay(payload), [])

    def test_canonical_world_replays_without_failures(self) -> None:
        payload = worlds.cached_world_readonly(CANONICAL_WORLD)

        self.assertEqual(validate_cultural_geography_replay(payload), [])

